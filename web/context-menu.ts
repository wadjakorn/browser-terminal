import type { Terminal } from '@xterm/xterm';

/**
 * เมนูคลิกขวาของเบราว์เซอร์ควรโผล่ไหม
 *
 * แยกสองกรณีตามว่าแอปข้างในขอ mouse reporting ไว้หรือไม่ ไม่ได้กดทิ้งทั้งหมด:
 *
 * - **ขอไว้** (`vt200`, `drag`, `any`, `x10`) — ปุ่มขวาเป็นของ TUI มันจะเปิดเมนูของ
 *   ตัวเองที่ตำแหน่งนั้น เมนูของเบราว์เซอร์ที่ทับขึ้นมาคือสิ่งที่ผู้ใช้ไม่ได้ขอและบัง
 *   เมนูจริงไว้ด้วย
 * - **ไม่ได้ขอ** (`none`) — ปล่อยเมนูของเบราว์เซอร์ไว้ตามเดิม เพราะนั่นคือวิธี
 *   คัดลอกข้อความบนเดสก์ท็อป xterm เติม textarea ให้เมนูนั้นพร้อมคัดลอกอยู่แล้ว
 *   ใน `rightClickHandler` (`Clipboard.ts:90-92`) การกดเมนูทิ้งเท่ากับพังการคัดลอก
 *   ของผู้ใช้เดสก์ท็อปเพื่อแลกกับอะไรก็ไม่รู้
 *
 * เรื่องนี้ไม่เกี่ยวกับปุ่ม RMB บนมือถือเลย — `MouseEvent` สังเคราะห์ไม่ทำให้
 * เบราว์เซอร์ยิง `contextmenu` ตั้งแต่แรก นี่เป็นของเมาส์จริงล้วนๆ
 */
export function suppressesContextMenu(mouseTrackingMode: Terminal['modes']['mouseTrackingMode']): boolean {
  return mouseTrackingMode !== 'none';
}
